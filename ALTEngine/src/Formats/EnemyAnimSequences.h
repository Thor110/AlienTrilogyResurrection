    // alongside the frame records in EnemyAnimData.h.
    //
    // FUN_0002f4b0 starts an animation from the pair at entity[+0x7c] +
    // index * 8: the frame table, and this sequence. The pairs for all 14
    // creatures sit at 0x000ac3a0..0x000aca78, in EnemyAnimData::CREATURES
    // order, and both pointers are offsets into the 0x90000 object. Each
    // sequence runs on the SpriteAnim VM (SpriteAnimator.h): entry 0 is the
    // frame duration in creature ticks, entry 1 is never shown, and frames and
    // control codes follow, up to the first OP_END, OP_END_ALT or OP_LOOP -
    // nothing after one of those is reachable.
    //
    // Generated by reading the image; not edited by hand.
