    std::optional<std::pair<int, int>> LookupSpriteFrameDimensions(const std::string& spriteName, int section, int frame)
    {
        const DimensionEntry* fallback = nullptr;
        for (const auto& entry : kDimensionTable)
        {
            if (spriteName != entry.name || entry.section != section) { continue; }
            if (entry.frame == frame) { return std::make_pair(entry.width, entry.height); }
            if (entry.frame == -1) { fallback = &entry; }
        }
        if (fallback) { return std::make_pair(fallback->width, fallback->height); }
        return std::nullopt;
    }
