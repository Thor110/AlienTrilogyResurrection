        // The three samples the manifests flag as looping.
        inline bool Loops(const char* name)
        {
            if (!name) { return false; }
            return std::strcmp(name, "0503-fla") == 0
                || std::strcmp(name, "4004ste0") == 0
                || std::strcmp(name, "3611lrun") == 0;
        }

        // Empty for a slot the level does not use. Callers should treat that as
        // "play nothing" rather than an error - the original pads with
        // blank.raw precisely so every id is always valid.
        inline const char* SlotName(const char* levelCode, int id)
        {
            if (!levelCode || id < 0 || static_cast<size_t>(id) >= SLOT_COUNT) { return ""; }
            for (const LevelTable& entry : LEVEL_TABLES)
            {
                if (std::strcmp(entry.code, levelCode) == 0)
                {
                    return NAMES[TABLES[entry.table][static_cast<size_t>(id)]];
                }
            }
            // Unknown level: fall back to table 0, whose first 0x29 slots are
            // the region every level shares anyway, so weapons, footsteps and
            // impacts still work.
            return NAMES[TABLES[0][static_cast<size_t>(id)]];
        }

        // "5004astp" -> "SFX/5004astp.RAW", relative to the CD directory.
        inline std::string SlotFile(const char* levelCode, int id)
        {
            const char* name = SlotName(levelCode, id);
            if (!name || name[0] == '\0') { return {}; }
            return std::string("SFX/") + name + ".RAW";
        }
