    // The sound bank, baked in.
    //
    // A sound id is a SLOT NUMBER. The original keeps the slot table on disc as
    // one NNNSFX.TXT per level - one line per slot, in order, with blank.raw
    // padding the slots that level does not use, 111 slots every time. Rather
    // than ship 45 loose text files alongside the game and rely on them being
    // present and unedited, those tables are compiled in here. Only the .RAW
    // samples are read at runtime, and only when something asks for one.
    //
    // HOW IT COMPRESSES. 45 levels x 111 slots is 4995 entries, but they use
    // only 103 distinct sample names and collapse to 34 distinct tables - the
    // five levels of 3.2.x share one outright, as do 1.1.3/4/5 and 9.0.3/4/5.
    // So this is a name pool plus 34 rows of byte indices, a few kilobytes of
    // constant data.
    //
    // WHAT VARIES BETWEEN LEVELS, measured rather than assumed:
    //   slots 0x00-0x28   identical everywhere. Menu, Ripley, all five weapons
    //                     and reloads, motion tracker, welder, nitrogen,
    //                     autogun, barrel, seismic, the three impact materials,
    //                     footstep, text beep, pickup.
    //   0x2a / 0x2b       the door family - 31xx, 32xx or 33xx by episode.
    //   0x2c              Ripley's own vocal - 0204 / 0206 / 0208 by episode.
    //   0x2d onwards      the enemy roster.
    //
    // THE "G" TABLES WERE USED WHERE THEY EXIST, and NEWSFX.BAT is why. The
    // plain tables put `enemyprf` at slot 0x1e and `smart3a2` at 0x1f, and
    // NEWSFX.BAT copies both of those onto THEMSELVES - a no-op copy, which is
    // what a build script contains when a placeholder is being held in place.
    // The G tables replace them with 0302puls and 0902smar. Note that level
    // 3.1.1's corrected table is named 311SXFG.TXT, not 311SFXG.TXT - a typo in
    // the original that a glob for "SFXG" silently misses.
    //
    // THE TRAILING NUMBER ON EACH MANIFEST LINE IS A LOOP FLAG. Across all 45
    // files it is only ever 0 or 1 (5521 zeros, 140 ones), and exactly three
    // samples ever carry the 1: 0503-fla (the flamethrower), 4004ste0 (steam)
    // and 3611lrun (a lift running). All three are continuous sounds, and no
    // sample appears with both values - so it is a property of the SAMPLE, not
    // of the slot, and it is stored that way below.
